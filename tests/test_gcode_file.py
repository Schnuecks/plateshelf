def test_prusa(tmp_path):
    path = tmp_path / "benchy.gcode"
    path.write_text(prusa_gcode())
    parsed = gcode_file.parse_gcode(path)
    assert parsed.slicer == "PrusaSlicer 2.8.1"
    assert parsed.printer == "Original Prusa MK4S"
    assert parsed.nozzle == "0.4" and parsed.layer_height == "0.2"
    assert parsed.process == "0.20mm SPEED @MK4S 0.4"
    plate = parsed.plates[0]
    assert plate.index == 1 and plate.sliced
    assert plate.prediction_s == 3723
    assert plate.layers == 2 and plate.max_z == 0.4
    assert [(f.slot, f.type, f.color, f.used_g, f.name, f.cost_per_kg) for f in plate.filaments] == [
        (1, "PLA", "#FF8000", 3.68, "Prusament PLA", 25.0), (2, "PETG", "#39B2B2", 0.3, "Prusament PETG", 30.0)]
    assert plate.filaments[0].used_m == 1.23
    assert plate.weight_g == pytest.approx(3.98)
    assert plate.objects == ["Benchy", "Benchy"]
    assert parsed.settings["fill_density"] == "15%" and parsed.settings["bed_temperature"] == ["60", "90"]
    # Größtes Vorschaubild, von QOI in PNG umgewandelt
    assert plate.thumb.startswith(b"\x89PNG")
    assert struct.unpack(">II", plate.thumb[16:24]) == (16, 16)


def test_qoi_to_png_pixels():
    png = gcode_file.qoi_to_png(qoi(2, 1, [(1, 2, 3, 255), (4, 5, 6, 7)]))
    raw = zlib.decompress(png[png.index(b"IDAT") + 4:png.index(b"IEND") - 8])
    assert raw == b"\x00" + bytes((1, 2, 3, 255, 4, 5, 6, 7))
    assert gcode_file.qoi_to_png(b"kein bild") is None


