def qoi(width, height, rgba):
    """Kleines QOI-Bild nur aus QOI_OP_RGBA-Blöcken."""
    body = b"".join(b"\xff" + bytes(px) for px in rgba)
    return b"qoif" + struct.pack(">IIBB", width, height, 4, 0) + body + b"\x00" * 7 + b"\x01"


def thumb_block(kind, width, height, data):
    b64 = base64.b64encode(data).decode()
    lines = [f"; {b64[i:i + 78]}" for i in range(0, len(b64), 78)]
    tag = "thumbnail" if kind == "PNG" else f"thumbnail_{kind}"
    return "\n".join([f"; {tag} begin {width}x{height} {len(b64)}", *lines, f"; {tag} end"])


def png_bytes():
    raw = b"\x00" + b"\xff\x00\x00\xff" * 2
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 2, 1, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw * 1)) + chunk(b"IEND", b""))


