def test_scan_and_names(lib, tmp_path):
    (lib / "Benchy_0.2mm_PLA_MK4S_1h2m.gcode").write_text(prusa_gcode())
    (lib / "Benchy_0.2mm_PLA_MK4S_1h2m.gcode").with_name("notiz.txt").write_text("x")
    store.scan(wait=True)
    with store.connect() as con:
        row = con.execute("SELECT f.id, f.printer, f.sliced, p.name FROM files f JOIN projects p ON p.id = f.project_id").fetchone()
        plate = con.execute("SELECT idx, has_thumb, prediction_s FROM plates WHERE file_id = ?", (row["id"],)).fetchone()
    assert row["printer"] == "Original Prusa MK4S" and row["sliced"] == 1
    assert row["name"] == "Benchy 0.2mm PLA MK4S 1h2m"
    assert tuple(plate) == (1, 1, 3723)
    assert (store.THUMB_DIR / str(row["id"]) / "plate_1.png").read_bytes().startswith(b"\x89PNG")
    assert store.unique_path(lib, "Benchy_0.2mm_PLA_MK4S_1h2m.gcode").name == "Benchy_0.2mm_PLA_MK4S_1h2m (2).gcode"


