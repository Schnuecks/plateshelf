"""Liest binären G-Code (.bgcode) von PrusaSlicer für Prusa MK4, XL, Mini und Core One.

Aufbau laut Spezifikation von libbgcode (github.com/prusa3d/libbgcode):
  Dateikopf   "GCDE", Version (uint32), Prüfsummenart (uint16: 0 keine, 1 CRC32)
  Blöcke      Typ (uint16), Kompression (uint16), Größe entpackt (uint32),
              Größe gepackt (uint32, nur wenn komprimiert), Parameter
              (Vorschaubild: Format, Breite, Höhe; sonst Kodierung, je uint16),
              Daten, Prüfsumme
Metadaten sind "key=value"-Zeilen, Vorschaubilder PNG, JPEG oder QOI. Der
G-Code steckt komprimiert (meist Heatshrink) und mit MeatPack gepackt in
G-Code-Blöcken. MeatPack kann Leerzeichen weglassen ("G1X10Y5E.4"), das
berücksichtigen die Leser in gcode_file und gcode_preview.
"""
from __future__ import annotations

import struct
import zlib
from dataclasses import dataclass, field
from pathlib import Path

import heatshrink2

MAGIC = b"GCDE"
FILE_META, GCODE, SLICER_META, PRINTER_META, PRINT_META, THUMBNAIL = range(6)
THUMB_FORMATS = {0: "PNG", 1: "JPG", 2: "QOI"}


def is_bgcode(name: str) -> bool:
    return name.lower().endswith(".bgcode")


@dataclass
class Meta:
    file: dict = field(default_factory=dict)
    printer: dict = field(default_factory=dict)
    print: dict = field(default_factory=dict)
    slicer: dict = field(default_factory=dict)
    thumbnails: list = field(default_factory=list)  # (Format, Breite, Höhe, Daten)

    def as_comments(self) -> str:
        """Metadaten im Stil der Kommentare einer .gcode-Datei, für denselben Leser."""
        lines = []
        if producer := self.file.get("Producer"):
            lines.append(f"; generated by {producer}")
        for part in (self.print, self.printer, self.slicer):
            lines += [f"; {k} = {v}" for k, v in part.items()]
        return "\n".join(lines) + "\n"


def _blocks(fh):
    """(Typ, Kompression, Größe entpackt, Größe gepackt, Parameter, Datenposition) je Block."""
    head = fh.read(10)
    if len(head) < 10 or head[:4] != MAGIC:
        raise ValueError("keine .bgcode-Datei")
    _version, checksum = struct.unpack("<IH", head[4:])
    crc_len = 4 if checksum == 1 else 0
    while True:
        raw = fh.read(8)
        if len(raw) < 8:
            return
        btype, comp, usize = struct.unpack("<HHI", raw)
        csize = struct.unpack("<I", fh.read(4))[0] if comp else usize
        params = fh.read(6 if btype == THUMBNAIL else 2)
        pos = fh.tell()
        yield btype, comp, usize, csize, params, pos
        fh.seek(pos + csize + crc_len)


def _unpack(raw: bytes, comp: int) -> bytes:
    if comp == 0:
        return raw
    if comp == 1:
        try:
            return zlib.decompress(raw)
        except zlib.error:
            return zlib.decompress(raw, -15)
    if comp in (2, 3):
        return heatshrink2.decompress(raw, window_sz2=11 if comp == 2 else 12, lookahead_sz2=4)
    raise ValueError(f"unbekannte Kompression {comp}")


def _ini(data: bytes) -> dict:
    out = {}
    for line in data.decode("utf-8", "replace").splitlines():
        key, sep, value = line.partition("=")
        if sep and key.strip():
            out[key.strip()] = value.strip()
    return out


def read_meta(path: Path) -> Meta:
    """Metadaten und Vorschaubilder; der G-Code wird übersprungen, das geht schnell."""
    meta = Meta()
    targets = {FILE_META: meta.file, PRINTER_META: meta.printer, PRINT_META: meta.print, SLICER_META: meta.slicer}
    with open(path, "rb") as fh:
        for btype, comp, _usize, csize, params, pos in _blocks(fh):
            if btype in targets:
                fh.seek(pos)
                targets[btype].update(_ini(_unpack(fh.read(csize), comp)))
            elif btype == THUMBNAIL:
                fmt, width, height = struct.unpack("<HHH", params)
                fh.seek(pos)
                meta.thumbnails.append((THUMB_FORMATS.get(fmt, "?"), width, height, _unpack(fh.read(csize), comp)))
    return meta


# --- MeatPack -----------------------------------------------------------------

_SIGNAL = 0xFF
_ENABLE_PACKING, _DISABLE_PACKING, _RESET, _ENABLE_NO_SPACES, _DISABLE_NO_SPACES = 251, 250, 249, 247, 246


def _tables(nospace: bool) -> tuple[list, list]:
    chars = list("0123456789.") + ["E" if nospace else " ", "\n", "G", "X", None]
    # Byte mit zwei gepackten Zeichen: fertiger Text; nach einem Zeilenende ist das zweite Füllung
    pair = []
    for b in range(256):
        lo, hi = chars[b & 15], chars[b >> 4]
        pair.append(None if lo is None or hi is None else (lo if lo == "\n" else lo + hi))
    return chars, pair


_TABLES = {False: _tables(False), True: _tables(True)}


class MeatPack:
    """Entpackt MeatPack (4 Bit je häufigem Zeichen), Zustand bleibt über Blöcke erhalten."""

    def __init__(self):
        self.packing = False
        self.nospace = False
        self.signal = False    # ein Signalbyte gesehen, das zweite macht daraus einen Befehl
        self.command = False   # nächstes Byte ist ein Befehl
        self.full = 0          # so viele ungepackte Zeichen folgen
        self.pending = ""      # zweites Zeichen, das nach dem ungepackten ausgegeben wird

    def _command(self, cmd: int) -> None:
        if cmd == _ENABLE_PACKING:
            self.packing = True
        elif cmd in (_DISABLE_PACKING, _RESET):
            self.packing = False
            if cmd == _RESET:
                self.nospace = False
        elif cmd == _ENABLE_NO_SPACES:
            self.nospace = True
        elif cmd == _DISABLE_NO_SPACES:
            self.nospace = False

    def decode(self, data: bytes) -> str:
        out: list[str] = []
        append = out.append
        chars, pair = _TABLES[self.nospace]

        def rx(b: int) -> None:
            if not self.packing:
                append(chr(b))
            elif self.full:
                append(chr(b))
                if self.pending:
                    append(self.pending)
                    self.pending = ""
                self.full -= 1
            else:
                lo, hi = chars[b & 15], chars[b >> 4]
                if lo is None:
                    self.full += 1
                    if hi is None:
                        self.full += 1
                    else:
                        self.pending = hi
                else:
                    append(lo)
                    if lo != "\n":
                        if hi is None:
                            self.full += 1
                        else:
                            append(hi)

        for b in data:
            if b == _SIGNAL:
                if self.signal:
                    self.command, self.signal = True, False
                else:
                    self.signal = True
                continue
            if self.command:
                self.command = False
                self._command(b)
                chars, pair = _TABLES[self.nospace]
                continue
            if self.signal:
                self.signal = False
                rx(_SIGNAL)
            if self.packing and not self.full and (s := pair[b]) is not None:
                append(s)  # häufigster Fall, ohne Funktionsaufruf
            else:
                rx(b)
        return "".join(out)


def gcode_lines(path: Path, progress=None):
    """G-Code-Zeilen der Datei (mit Zeilenende); progress(0..1) nach jedem Block."""
    with open(path, "rb") as fh:
        total = fh.seek(0, 2) or 1
        fh.seek(0)
        packer, rest = MeatPack(), ""
        for btype, comp, _usize, csize, params, pos in _blocks(fh):
            if btype != GCODE:
                continue
            fh.seek(pos)
            data = _unpack(fh.read(csize), comp)
            encoding = struct.unpack("<H", params)[0]
            text = rest + (packer.decode(data) if encoding in (1, 2) else data.decode("utf-8", "replace"))
            lines = text.split("\n")
            rest = lines.pop()
            for line in lines:
                yield line + "\n"
            if progress:
                progress((pos + csize) / total)
        if rest:
            yield rest + "\n"
